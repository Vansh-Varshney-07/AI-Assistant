/** Inspect the packaged files without executing Electron or opening a window. */
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { readFile, readdir, open, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { listPackage, extractFile } from '@electron/asar';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('..', import.meta.url));
const packaged = path.join(root, 'release/win-unpacked');
const archive = path.join(packaged, 'resources/app.asar');
const files = listPackage(archive).map(p => p.replaceAll('\\', '/'));
const hash = async p => { const h = createHash('sha256'); for await (const block of createReadStream(p)) h.update(block); return h.digest('hex'); };
const checks = [];
const check = (name, value) => { assert(value, name); checks.push({ name, passed: true }); };
for (const file of ['/dist/main/index.js', '/dist/preload/index.cjs', '/dist/renderer/index.html']) check('packaged:' + file, files.includes(file));
const fromArchive = p => extractFile(archive, path.normalize(p));
const metadata = JSON.parse(fromArchive('package.json').toString());
check('esm_main_entry', metadata.main === 'dist/main/index.js' && metadata.type === 'module');
check('no_private_runtime_or_fixture_in_archive', !files.some(p => /\/(\.env(?:\.[^/]+)?|credentials\.json|token\.json|app\.sqlite3|test-results|\.cache)(\/|$)/i.test(p)));
const main = fromArchive('dist/main/index.js').toString();
check('renderer_isolation_flags', main.includes('contextIsolation: true') && main.includes('nodeIntegration: false') && main.includes('sandbox: true'));
const page = fromArchive('dist/renderer/index.html').toString();
check('production_csp_no_network_or_inline_script', page.includes("connect-src 'none'") && page.includes("script-src 'self'") && !page.includes("script-src 'unsafe-inline'"));
const scripts = files.filter(p => p.startsWith('/dist/renderer/') && p.endsWith('.js')).map(p => fromArchive(p.slice(1)).toString()).join('\n');
check('no_renderer_bootstrap_secret_or_bearer', !scripts.includes('WAYFINDER_HOST_SECRET') && !scripts.includes('Bearer '));
const sourceHost = path.join(root, 'backend/host.py'), packagedHost = path.join(packaged, 'resources/backend/host.py');
check('packaged_backend_matches_source', await hash(sourceHost) === await hash(packagedHost));
check('only_host_python_packaged', JSON.stringify((await readdir(path.dirname(packagedHost))).sort()) === JSON.stringify(['host.py']));
const executable = path.join(packaged, 'Wayfinder.exe');
const handle = await open(executable); const signature = Buffer.alloc(2); await handle.read(signature, 0, 2, 0); await handle.close();
check('windows_pe_executable', signature.toString() === 'MZ');
const ui = JSON.parse(await readFile(path.join(root, 'test-results/ui.json'), 'utf8'));
check('frontend_test_report_passed', ui.numFailedTests === 0 && ui.numPassedTests > 0);
const live = JSON.parse(await readFile(path.join(root, 'test-results/actual-transport.json'), 'utf8'));
const node = JSON.parse(await readFile(path.join(root, 'test-results/node-bridge.json'), 'utf8'));
check('real_neural_and_hermes_evidence', live.actual_neural_embeddings && live.live_hermes?.status === 'completed' && live.checks.every(c => c.passed));
check('production_node_bridge_evidence', node.checks.every(c => c.passed));
const evidence = { build: 'wayfinder-desktop/0.1', generated: new Date().toISOString(), scope: 'static package inspection; Electron was not launched', checks, passed: checks.length, frontend: { passed: ui.numPassedTests, failed: ui.numFailedTests }, real_neural_hermes_checks: live.passed, production_node_bridge_checks: node.passed, packaged_host_sha256: await hash(packagedHost), asar_sha256: await hash(archive), executable_sha256: await hash(executable), application_version: metadata.version, native_or_visual_tests_run: false, google_account_tests_run: false };
await writeFile(path.join(root, 'build-evidence.json'), JSON.stringify(evidence, null, 2) + '\n');
console.log(JSON.stringify(evidence));
